#!/usr/bin/env python3
"""Generate sks_wmm_coeffs.c from a WMM .COF coefficient file (NOAA, public domain).

  python3 plant/sensors/gen_wmm_coeffs.py /Applications/MATLAB_R2026b.app/toolbox/aero/aero/private/WMM2025.COF

The default source is the copy that ships with MATLAB R2026b (no download). The generated file
records the source path and SHA-256; do not edit it by hand.
"""
import hashlib
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / 'sks_wmm_coeffs.c'


def main():
    source = Path(sys.argv[1] if len(sys.argv) > 1 else
                  '/Applications/MATLAB_R2026b.app/toolbox/aero/aero/private/WMM2025.COF')
    text = source.read_text()
    lines = text.splitlines()
    header = lines[0].split()
    epoch, name = float(header[0]), header[1]
    rows = []
    for line in lines[1:]:
        if line.startswith('9999'):
            break
        n, m, g, h, dg, dh = line.split()
        rows.append((int(n), int(m), g, h, dg, dh))
    degree = max(r[0] for r in rows)
    if len(rows) != degree * (degree + 3) // 2:
        raise SystemExit(f'unexpected coefficient count {len(rows)} for degree {degree}')
    body = ',\n'.join(f'  {{{n}, {m}, {g}, {h}, {dg}, {dh}}}' for n, m, g, h, dg, dh in rows)
    OUT.write_text(f'''/* Generated by plant/sensors/gen_wmm_coeffs.py; do not edit.
 * Source: {source}
 * SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}
 * Model: {name}, epoch {epoch}. World Magnetic Model coefficients (NOAA NCEI / BGS), public domain.
 * Columns: n, m, g (nT), h (nT), g dot (nT/yr), h dot (nT/yr). */
#include "sks_wmm.h"

const double sks_wmm_epoch = {epoch};
const char sks_wmm_name[] = "{name}";
const SksWmmCoeff sks_wmm_coeffs[SKS_WMM_COEFF_COUNT] = {{
{body}
}};
''')
    print(f'wrote {OUT} ({name}, epoch {epoch}, degree {degree}, {len(rows)} terms)')


if __name__ == '__main__':
    main()
