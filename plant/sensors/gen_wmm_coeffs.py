#!/usr/bin/env python3
"""Generate plant_wmm_coeffs.c from a WMM .COF coefficient file (NOAA, public domain).

  python3 plant/sensors/gen_wmm_coeffs.py <MATLAB root>/toolbox/aero/aero/private/WMM2025.COF

Use the copy that ships with MATLAB (Aerospace Blockset; no download). The generated file records the file name
and SHA-256 of the source; do not edit it by hand.
"""
import hashlib
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / 'plant_wmm_coeffs.c'


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    source = Path(sys.argv[1])
    text = source.read_text()
    lines = text.splitlines()
    header = lines[0].split()
    epoch, name = float(header[0]), header[1]
    rows = []
    for line in lines[1:]:
        if line.startswith('9999'):
            break
        n, m, g, h, dg, dh = line.split()
        rows.append((int(n), int(m), g, h, dg, dh))
    degree = max(r[0] for r in rows)
    if len(rows) != degree * (degree + 3) // 2:
        raise SystemExit(f'unexpected coefficient count {len(rows)} for degree {degree}')
    body = ',\n'.join(f'  {{{n}, {m}, {g}, {h}, {dg}, {dh}}}' for n, m, g, h, dg, dh in rows)
    OUT.write_text(f'''/* Generated by plant/sensors/gen_wmm_coeffs.py; do not edit.
 * Source: <MATLAB root>/toolbox/aero/aero/private/{source.name}
 * SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}
 * Model: {name}, epoch {epoch}. World Magnetic Model coefficients (NOAA NCEI / BGS), public domain.
 * Columns: n, m, g (nT), h (nT), g dot (nT/yr), h dot (nT/yr). */
#include "plant_wmm.h"

const double plant_wmm_epoch = {epoch};
const char plant_wmm_name[] = "{name}";
const PlantWmmCoeff plant_wmm_coeffs[PLANT_WMM_COEFF_COUNT] = {{
{body}
}};
''')
    print(f'wrote {OUT} ({name}, epoch {epoch}, degree {degree}, {len(rows)} terms)')


if __name__ == '__main__':
    main()
